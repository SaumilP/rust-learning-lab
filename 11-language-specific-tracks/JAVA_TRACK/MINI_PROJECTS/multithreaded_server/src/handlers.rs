/// Static file handler
pub fn static_file_handler(file_path: &str) -> impl Fn(&Request) -> Response + '_ {
    move |_req: &Request| {
        // Security: prevent directory traversal
        if file_path.contains("..") {
            return Response::new(StatusCode::BadRequest)
                .body("Invalid file path".to_string());
        }

        let full_path = Path::new("static").join(file_path);

        match fs::read_to_string(&full_path) {
            Ok(contents) => {
                // Determine content type from extension
                let content_type = match full_path.extension().and_then(|s| s.to_str()) {
                    Some("html") => "text/html",
                    Some("css") => "text/css",
                    Some("js") => "application/javascript",
                    Some("json") => "application/json",
                    Some("png") => "image/png",
                    Some("jpg") | Some("jpeg") => "image/jpeg",
                    _ => "text/plain",
                };

                Response::new(StatusCode::OK)
                    .content_type(content_type)
                    .body(contents)
            }
            Err(_) => Response::new(StatusCode::NotFound)
                .content_type("text/html")
                .body("<h1>404 - File Not Found</h1>".to_string()),
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::collections::HashMap;
    use crate::http::Method;

    fn create_test_request() -> Request {
        Request {
            method: Method::GET,
            path: "/".to_string(),
            version: "HTTP/1.1".to_string(),
            headers: HashMap::new(),
            body: String::new(),
        }
    }

    #[test]
    fn test_home_handler() {
        let req = create_test_request();
        let response = home_handler(&req);
        assert!(response.get_body().contains("Multithreaded HTTP Server"));
    }

    #[test]
    fn test_hello_handler() {
        let req = create_test_request();
        let response = hello_handler(&req);
        assert!(response.get_body().contains("Hello from Rust"));
    }

    #[test]
    fn test_connection_counter() {
        let counter = ConnectionCounter::new();
        assert_eq!(counter.get_count(), 0);

        counter.increment();
        assert_eq!(counter.get_count(), 1);

        counter.increment();
        assert_eq!(counter.get_count(), 2);
    }

    #[test]
    fn test_stats_handler() {
        let counter = ConnectionCounter::new();
        counter.increment();
        counter.increment();

        let handler = stats_handler(counter);
        let req = create_test_request();
        let response = handler(&req);

        assert!(response.get_body().contains("2"));
    }
}
