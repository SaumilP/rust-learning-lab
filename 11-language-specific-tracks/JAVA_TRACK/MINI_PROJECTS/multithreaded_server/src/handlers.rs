/// Slow endpoint that simulates expensive computation
pub fn sleep_handler(_req: &Request) -> Response {
    use std::thread;
    use std::time::Duration;

    println!("Sleeping for 5 seconds...");
    thread::sleep(Duration::from_secs(5));

    Response::new(StatusCode::OK)
        .content_type("text/plain")
        .body("I'm awake now! (slept for 5 seconds)".to_string())
}

